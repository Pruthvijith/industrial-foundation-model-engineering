"""Constrained four-action GRPO, a synthetic reward head and a distilled router."""

import argparse
import json
import os
from pathlib import Path
import random
import torch
from torch import nn
from peft import PeftModel
from transformers import AutoModelForCausalLM, AutoTokenizer
from .data import LETTERS, cases
from .experiment import choice_tokens, predictions


def advantages(rewards):
    """A constant-reward group contributes zero policy-gradient signal."""
    return (rewards - rewards.mean(-1, keepdim=True)) / rewards.std(
        -1, keepdim=True, unbiased=False
    ).clamp_min(1e-6)


def clipped_objective(logp, old, actions, adv, reference):
    selected = logp.gather(1, actions)
    ratio = (selected - old).exp()
    advantage_term = torch.minimum(ratio * adv, ratio.clamp(0.8, 1.2) * adv).mean()
    kl = (logp.exp() * (logp - reference)).sum(-1).mean()
    return -advantage_term + 0.03 * kl


class Student(nn.Module):
    """Small prompt classifier for distillation into a fixed answer space."""

    def __init__(self):
        super().__init__()
        self.embedding = nn.Embedding(2048, 32)
        self.core = nn.GRU(32, 32, batch_first=True)
        self.out = nn.Linear(32, 4)

    def forward(self, ids, mask):
        seq, _ = self.core(self.embedding(ids % 2048))
        return self.out(seq[torch.arange(len(ids)), mask.sum(-1) - 1])


def features_and_scores(model, enc, ids):
    """Project only the final hidden states onto the four admissible actions."""
    base = model.get_base_model()
    states = base.model(**enc, use_cache=False).last_hidden_state
    last = states[torch.arange(len(states)), enc.attention_mask.sum(1) - 1]
    return last, nn.functional.linear(last, base.lm_head.weight[ids])


def run(src, rev, adapter, out):
    out.mkdir(parents=True, exist_ok=False)
    torch.manual_seed(9001)
    torch.set_num_threads(2)
    rng = random.Random(9001)
    tok = AutoTokenizer.from_pretrained(src, revision=rev)
    tok.pad_token = tok.eos_token
    model = PeftModel.from_pretrained(
        AutoModelForCausalLM.from_pretrained(src, revision=rev, use_safetensors=True),
        adapter,
        is_trainable=True,
    )
    model.eval()
    token_ids = choice_tokens(tok)
    train = cases("train", 24)
    test = cases("test", 12)
    rows = train + test
    reference = []
    hidden = []
    with torch.no_grad():
        for i in range(0, len(rows), 4):
            enc = tok([r["prompt"] for r in rows[i : i + 4]], padding=True, return_tensors="pt")
            last, logits = features_and_scores(model, enc, token_ids)
            reference.append(logits.log_softmax(-1))
            hidden.append(last)

    ref = torch.cat(reference)
    features = torch.cat(hidden)
    # All ranks are generated by the task oracle. No human feedback enters training.
    reward = nn.Linear(features.shape[-1], 4)
    student = Student()
    ropt = torch.optim.AdamW(reward.parameters(), lr=0.003)
    sopt = torch.optim.AdamW(student.parameters(), lr=0.004)
    all_tokens = tok([r["prompt"] for r in rows], padding=True, return_tensors="pt")
    pos = torch.tensor([LETTERS.index(r["target"]) for r in rows])
    neg = torch.tensor([LETTERS.index(r["rejected"]) for r in rows])
    for _ in range(50):
        idx = torch.randperm(len(train))[:12]
        score = reward(features[idx])
        ar = torch.arange(len(idx))
        loss = -nn.functional.logsigmoid(score[ar, pos[idx]] - score[ar, neg[idx]]).mean()
        ropt.zero_grad()
        loss.backward()
        ropt.step()
        z = student(all_tokens.input_ids[idx], all_tokens.attention_mask[idx])
        target = (ref[idx] / 2).softmax(-1)
        kd = 4 * nn.functional.kl_div((z / 2).log_softmax(-1), target, reduction="batchmean")
        sopt.zero_grad()
        kd.backward()
        sopt.step()
    opt = torch.optim.AdamW([p for p in model.parameters() if p.requires_grad], lr=0.0001)
    nonconstant = 0
    for _ in range(10):
        idx = rng.sample(range(len(train)), 4)
        prompts = [train[i]["prompt"] for i in idx]
        with torch.no_grad():
            policy = features_and_scores(model, tok(prompts, padding=True, return_tensors="pt"), token_ids)[
                1
            ].log_softmax(-1)
            actions = torch.multinomial(policy.exp(), 8, replacement=True)
            old = policy.gather(1, actions)
            rewards = actions.eq(pos[idx, None]).float()
            adv = advantages(rewards)
            nonconstant += int((adv.abs().sum(1) > 0).sum())
        for _ in range(2):
            current = features_and_scores(model, tok(prompts, padding=True, return_tensors="pt"), token_ids)[
                1
            ].log_softmax(-1)
            loss = clipped_objective(current, old, actions, adv, ref[idx])
            opt.zero_grad()
            loss.backward()
            nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            opt.step()
    preds = predictions(model, tok, test, token_ids, 4)
    with torch.no_grad():
        ix = torch.arange(len(train), len(rows))
        ar = torch.arange(len(ix))
        scores = reward(features[ix])
        small = student(all_tokens.input_ids[ix], all_tokens.attention_mask[ix]).argmax(-1)
    metrics = dict(
        seed=9001,
        train_n=len(train),
        test_n=len(test),
        groups_sampled=40,
        informative_groups=nonconstant,
        grpo_accuracy=sum(r["prediction"] == r["target"] for r in preds) / len(test),
        reward_pair_accuracy=float((scores[ar, pos[ix]] > scores[ar, neg[ix]]).float().mean()),
        student_domain_accuracy=float((small == pos[ix]).float().mean()),
        student_teacher_agreement=float((small == ref[ix].argmax(-1)).float().mean()),
        student_parameters=sum(p.numel() for p in student.parameters()),
        teacher="frozen SFT reference",
        scope="four allowed completions; synthetic preferences; one training seed",
    )
    from safetensors.torch import save_model

    save_model(student, str(out / "student.safetensors"))
    save_model(reward, str(out / "reward.safetensors"))
    model.save_pretrained(out / "grpo")
    (out / "metrics.json").write_text(json.dumps(metrics, indent=2) + "\n")
    (out / "predictions.json").write_text(json.dumps(preds, indent=2) + "\n")


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--config", type=Path, default=Path("configs/cpu.json"))
    p.add_argument("adapter", type=Path)
    p.add_argument("out", type=Path)
    a = p.parse_args()
    c = json.loads(a.config.read_text())
    run(os.getenv("LOCAL_MODEL", c["model"]), c["revision"], a.adapter, a.out)
